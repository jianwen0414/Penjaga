"""Compare fault-free simulated houses with sourced aggregates and write a Markdown report.

    uv run python services/sim/tools/validation_report.py      # docs/reports/sim-validation.md
    uv run python services/sim/tools/validation_report.py --days 7 --seeds 1 2

Each (seed, archetype) world runs ``--days`` days starting the day after START (the first day
tops up the roof tank from its random starting level, which is not consumption).
"""

from __future__ import annotations

import argparse
import statistics
from collections import defaultdict
from datetime import date, timedelta
from pathlib import Path

import numpy as np

from penjaga_contract.core import Fixture
from penjaga_sim import GENERATOR_VERSION
from penjaga_sim.calibration import load_calibration
from penjaga_sim.household import plan_day
from penjaga_sim.testing import START, new_world

ROOT = Path(__file__).resolve().parents[3]
DS012 = 241.0  # L/person/day, Selangor/KL/Putrajaya 2023
DS013 = {"shower": 124.8, "toileting": 62.6, "hand washing and teeth": 31.5, "dish washing": 30.0}
DS013_TOTAL = 288.0
DS014 = (345.0, 648.31)  # kWh/month, two household surveys
END_USE = {
    "shower": "shower",
    "wc_cistern": "toileting",
    "bidet_spray": "toileting",
    "basin_tap": "hand washing and teeth",
    "sink_tap": "kitchen sinks (incl. dish washing)",
    "washing_machine_tap": "laundry",
    "laundry_tap": "laundry",
    "garden_tap": "outdoor",
}


def run(seeds: list[int], days: int) -> str:
    cal = load_calibration()
    archetypes = sorted(cal.table("household.archetypes"))
    rows = []
    end_use: dict[str, float] = defaultdict(float)
    person_days = 0.0
    pressure: list[float] = []
    voltage: list[float] = []
    trips = 0
    for seed in seeds:
        for archetype in archetypes:
            world = new_world(seed=seed, archetype=archetype)
            litres, kwh = [], []
            for k in range(1, days + 1):
                day = START + timedelta(days=k)
                out = world.output(day)
                s = out.summary
                litres.append(s["water_true_l"] / s["occupants"])
                kwh.append(s["energy_kwh"])
                trips += len(out.events)
                pressure += [
                    float(np.nanmin(out.streams["water.main.pressure_bar"].values)),
                    float(np.nanmax(out.streams["water.main.pressure_bar"].values)),
                ]
                voltage += [
                    float(np.nanmin(out.streams["elec.main.voltage_v"].values)),
                    float(np.nanmax(out.streams["elec.main.voltage_v"].values)),
                ]
                plan = plan_day(world.model, archetype, day)
                person_days += len(plan.occupants)
                for u in plan.water:
                    kind = world.model.index.get(u.fixture, Fixture).kind.value
                    end_use[END_USE.get(kind, kind)] += u.lpm * u.dur / 60
            rows.append((seed, archetype, statistics.mean(litres), 30.4 * statistics.mean(kwh)))
    water = [r[2] for r in rows]
    energy = [r[3] for r in rows]
    scale = DS012 / DS013_TOTAL

    def spread(xs: list[float], fmt: str) -> str:
        return f"{statistics.mean(xs):{fmt}} ({min(xs):{fmt}}-{max(xs):{fmt}})"

    first = (START + timedelta(days=1)).isoformat()
    lines = [
        "---",
        "type: report",
        "status: generated",
        f"created: {date.today().isoformat()}",
        "modules: [M2]",
        "tags: [penjaga, simulator, validation]",
        "---",
        "",
        "# Simulator validation against sourced aggregates",
        "",
        "Generated by `services/sim/tools/validation_report.py` with generator "
        f"`{GENERATOR_VERSION}`: seeds {seeds}, {len(archetypes)} household archetypes, "
        f"{days} fault-free days each from {first}. "
        "Sources: [DATA_SOURCES.md](../DATA_SOURCES.md).",
        "",
        "## Summary",
        "",
        "| Quantity | Simulated mean (range over worlds) | Reference |",
        "|---|---|---|",
        f"| Water, L/person/day | {spread(water, '.0f')} "
        f"| {DS012:.0f} (DS-012); 288 (DS-013, older survey) |",
        f"| Electricity, kWh/month | {spread(energy, '.0f')} "
        f"| {DS014[0]:.0f} and {DS014[1]:.0f} (DS-014, two surveys) |",
        f"| Supply pressure, bar | {min(pressure):.2f}-{max(pressure):.2f} "
        "| design band (DS-018) |",
        f"| Supply voltage, V | {min(voltage):.1f}-{max(voltage):.1f} "
        "| 216-253 statutory (DS-022) |",
        f"| Protective-device trips without faults | {trips} | 0 expected |",
        "",
        "## Per world",
        "",
        "| Seed | Archetype | L/person/day | kWh/month |",
        "|---|---|---|---|",
        *[f"| {s} | {a} | {w:.0f} | {e:.0f} |" for s, a, w, e in rows],
        "",
        "## Water end uses (L/person/day)",
        "",
        f"DS-013 shares scaled to the DS-012 level (x{scale:.2f}) give the shape to compare with.",
        "",
        "| End use | Simulated | DS-013 scaled to DS-012 |",
        "|---|---|---|",
    ]
    for use, litres_total in sorted(end_use.items(), key=lambda kv: -kv[1]):
        ref = DS013.get(use)
        ref_text = f"{ref * scale:.0f}" if ref is not None else "-"
        lines.append(f"| {use} | {litres_total / person_days:.1f} | {ref_text} |")
    lines += [
        "",
        "## Reading the gaps",
        "",
        "- Toileting is the largest gap. The modelled house is a new build with 6/3 L dual-flush",
        "  cisterns (an assumption). DS-013 does not state its fixtures; its 62.6 L/person/day is",
        "  consistent with older 9 L single-flush cisterns (our inference). DS-012 is a state",
        "  average over all housing stock, including in-premises losses. Not tuned away: no",
        "  source supports a higher WC volume for this house.",
        "- Electricity is 13% below the lower survey (DS-014, 345 kWh/month) and well below the",
        "  Seremban urban survey (648). Aircon use depends on the weather of the simulated weeks;",
        "  aircon parameters are assumptions and the first candidates if real data disagree.",
        "- Every behaviour parameter behind these totals is listed with its basis in",
        "  `services/sim/src/penjaga_sim/calibration/*.toml`.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    parser.add_argument("--seeds", type=int, nargs="+", default=[1, 2, 3])
    parser.add_argument("--days", type=int, default=14)
    parser.add_argument("--out", type=Path, default=ROOT / "docs" / "reports" / "sim-validation.md")
    args = parser.parse_args()
    report = run(args.seeds, args.days)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(report, encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
